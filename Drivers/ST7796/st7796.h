/*
 * ST7796 TFT Display Driver
 * Resolution: 480x320 (native)
 * Interface:  SPI
 *
 * GPIO pin setup in STM32CubeMX:
 *   Assign User Labels to the GPIO output pins:
 *     ST7796_DC   -> Data/Command select
 *     ST7796_RST  -> Reset (active low)
 *     ST7796_CS   -> Chip select (active low)
 *                    OR tie CS permanently to GND and define CFG_NO_CS below
 *
 * Example CubeMX label → this driver's macros:
 *   PA1 labeled "ST7796_DC"  → ST7796_DC_GPIO_Port / ST7796_DC_Pin  (auto-generated in main.h)
 *   PA2 labeled "ST7796_RST" → ST7796_RST_GPIO_Port / ST7796_RST_Pin
 *   PA3 labeled "ST7796_CS"  → ST7796_CS_GPIO_Port  / ST7796_CS_Pin
 */

/* SPI peripheral handle - change to hspi2/hspi3 if needed */
#define ST7796_SPI_PORT hspi1
extern SPI_HandleTypeDef ST7796_SPI_PORT;

/* Uncomment to enable DMA for bulk transfers (faster fills / image draws).
 * Requires the SPI DMA Tx channel to be enabled in CubeMX. */
// #define ST7796_USE_DMA

/* Uncomment if CS is hard-wired to GND (no software CS control needed) */
// #define ST7796_CFG_NO_CS

/* Display dimensions */
#define ST7796_WIDTH    480
#define ST7796_HEIGHT   320

/* Default rotation: 0=portrait, 1=landscape, 2=portrait inverted, 3=landscape inverted */
#define ST7796_ROTATION 1

/* ST7796 command registers */
#define ST7796_NOP          0x00
#define ST7796_SWRESET      0x01
#define ST7796_SLPIN        0x10
#define ST7796_SLPOUT       0x11
#define ST7796_NORON        0x13
#define ST7796_INVOFF       0x20
#define ST7796_INVON        0x21
#define ST7796_DISPOFF      0x28
#define ST7796_DISPON       0x29
#define ST7796_CASET        0x2A
#define ST7796_RASET        0x2B
#define ST7796_RAMWR        0x2C
#define ST7796_MADCTL       0x36
#define ST7796_COLMOD       0x3A

/* MADCTL rotation bits */
#define ST7796_MADCTL_MY    0x80
#define ST7796_MADCTL_MX    0x40
#define ST7796_MADCTL_MV    0x20
#define ST7796_MADCTL_ML    0x10
#define ST7796_MADCTL_BGR   0x08
#define ST7796_MADCTL_MH    0x04

/* GPIO pin control macros.
 * Pin names are auto-generated by CubeMX from the User Label you assign. */
#define ST7796_RST_Set()    HAL_GPIO_WritePin(ST7796_RST_GPIO_Port, ST7796_RST_Pin, GPIO_PIN_SET)
#define ST7796_RST_Clr()    HAL_GPIO_WritePin(ST7796_RST_GPIO_Port, ST7796_RST_Pin, GPIO_PIN_RESET)
#define ST7796_DC_Set()     HAL_GPIO_WritePin(ST7796_DC_GPIO_Port,  ST7796_DC_Pin,  GPIO_PIN_SET)
#define ST7796_DC_Clr()     HAL_GPIO_WritePin(ST7796_DC_GPIO_Port,  ST7796_DC_Pin,  GPIO_PIN_RESET)

#ifndef ST7796_CFG_NO_CS
#define ST7796_CS_Clr()     HAL_GPIO_WritePin(ST7796_CS_GPIO_Port,  ST7796_CS_Pin,  GPIO_PIN_RESET)
#define ST7796_CS_Set()     HAL_GPIO_WritePin(ST7796_CS_GPIO_Port,  ST7796_CS_Pin,  GPIO_PIN_SET)
#else
#define ST7796_CS_Clr()     do {} while(0)
#define ST7796_CS_Set()     do {} while(0)
#endif

/* Public API */
void     ST7796_Init(void);
void     ST7796_SetRotation(uint8_t rot);
void     ST7796_InvertColors(uint8_t invert);

void     ST7796_FillScreen(uint16_t color);
void     ST7796_Fill(uint16_t x0, uint16_t y0, uint16_t x1, uint16_t y1, uint16_t color);
void     ST7796_DrawPixel(uint16_t x, uint16_t y, uint16_t color);

void     ST7796_DrawLine(uint16_t x0, uint16_t y0, uint16_t x1, uint16_t y1, uint16_t color);
void     ST7796_DrawRectangle(uint16_t x0, uint16_t y0, uint16_t x1, uint16_t y1, uint16_t color);
void     ST7796_DrawFilledRectangle(uint16_t x, uint16_t y, uint16_t w, uint16_t h, uint16_t color);
void     ST7796_DrawCircle(int16_t x0, int16_t y0, int16_t r, uint16_t color);
void     ST7796_DrawFilledCircle(int16_t x0, int16_t y0, int16_t r, uint16_t color);

void     ST7796_DrawImage(uint16_t x, uint16_t y, uint16_t w, uint16_t h, const uint16_t *data);
void     ST7796_DrawImageSwapRB(uint16_t x, uint16_t y, uint16_t w, uint16_t h, const uint16_t *data);
void     ST7796_FadeIn(uint16_t x, uint16_t y, uint16_t w, uint16_t h, const uint16_t *data, uint8_t steps, uint16_t step_delay_ms);
void     ST7796_WriteChar(uint16_t x, uint16_t y, char ch, FontDef font, uint16_t color, uint16_t bgcolor);
void     ST7796_WriteString(uint16_t x, uint16_t y, const char *str, FontDef font, uint16_t color, uint16_t bgcolor);
