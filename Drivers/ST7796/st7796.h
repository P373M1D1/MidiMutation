/*
 * ST7796 TFT Display Driver
 * Resolution: 480x320 (native)
 * Interface:  SPI
 *
 * GPIO pin setup:
 *   The driver consumes the GPIO and SPI symbols exported via main.h.
 *   Those symbols may come from CubeMX generation or from manual project
 *   maintenance, as long as the names remain compatible.
 *
 *   Typical pin labels are:
 *     ST7796_DC   -> Data/Command select
 *     ST7796_RST  -> Reset (active low)
 *     ST7796_CS   -> Chip select (active low)
 *                    OR tie CS permanently to GND and define CFG_NO_CS below
 *
 * Example CubeMX label → this driver's macros:
 *   PA1 labeled "ST7796_DC"  → ST7796_DC_GPIO_Port / ST7796_DC_Pin  (auto-generated in main.h)
 *   PA2 labeled "ST7796_RST" → ST7796_RST_GPIO_Port / ST7796_RST_Pin
 *   PA3 labeled "ST7796_CS"  → ST7796_CS_GPIO_Port  / ST7796_CS_Pin
 */

/* SPI peripheral handle - change to hspi2/hspi3 if needed */
#define ST7796_SPI_PORT hspi1 /* SPI handle used by the ST7796 driver */
extern SPI_HandleTypeDef ST7796_SPI_PORT;

/* Uncomment to enable DMA for bulk transfers (faster fills / image draws).
 * In this project SPI1 TX DMA is configured manually in stm32f4xx_hal_msp.c,
 * not regenerated from CubeMX. */
#define ST7796_USE_DMA

/* Uncomment if CS is hard-wired to GND (no software CS control needed) */
// #define ST7796_CFG_NO_CS

/* Display dimensions */
#define ST7796_WIDTH    480 /* native display width in pixels */
#define ST7796_HEIGHT   320 /* native display height in pixels */

/* Default rotation: 0=portrait, 1=landscape, 2=portrait inverted, 3=landscape inverted */
#define ST7796_ROTATION 3 /* default panel rotation used during initialization */

/* ST7796 command registers */
#define ST7796_NOP          0x00 /* controller no-operation command */
#define ST7796_SWRESET      0x01 /* controller software-reset command */
#define ST7796_SLPIN        0x10 /* command that puts the panel into sleep mode */
#define ST7796_SLPOUT       0x11 /* command that wakes the panel from sleep mode */
#define ST7796_NORON        0x13 /* command that switches the panel to normal display mode */
#define ST7796_INVOFF       0x20 /* command that disables display colour inversion */
#define ST7796_INVON        0x21 /* command that enables display colour inversion */
#define ST7796_DISPOFF      0x28 /* command that turns the display output off */
#define ST7796_DISPON       0x29 /* command that turns the display output on */
#define ST7796_CASET        0x2A /* command that sets the column address window */
#define ST7796_RASET        0x2B /* command that sets the row address window */
#define ST7796_RAMWR        0x2C /* command that writes pixel data into GRAM */
#define ST7796_MADCTL       0x36 /* command that controls address order and colour order */
#define ST7796_COLMOD       0x3A /* command that selects the pixel format */

/* MADCTL rotation bits */
#define ST7796_MADCTL_MY    0x80 /* MADCTL bit that mirrors the row order */
#define ST7796_MADCTL_MX    0x40 /* MADCTL bit that mirrors the column order */
#define ST7796_MADCTL_MV    0x20 /* MADCTL bit that swaps row/column addressing */
#define ST7796_MADCTL_ML    0x10 /* MADCTL bit that flips vertical refresh order */
#define ST7796_MADCTL_BGR   0x08 /* MADCTL bit that selects BGR colour order */
#define ST7796_MADCTL_MH    0x04 /* MADCTL bit that flips horizontal refresh order */

/* GPIO pin control macros.
 * Pin names are auto-generated by CubeMX from the User Label you assign. */
#define ST7796_RST_Set()    HAL_GPIO_WritePin(ST7796_RST_GPIO_Port, ST7796_RST_Pin, GPIO_PIN_SET) /* drive the display reset line inactive */
#define ST7796_RST_Clr()    HAL_GPIO_WritePin(ST7796_RST_GPIO_Port, ST7796_RST_Pin, GPIO_PIN_RESET) /* drive the display reset line active */
#define ST7796_DC_Set()     HAL_GPIO_WritePin(ST7796_DC_GPIO_Port,  ST7796_DC_Pin,  GPIO_PIN_SET) /* select SPI data mode for the next transfer */
#define ST7796_DC_Clr()     HAL_GPIO_WritePin(ST7796_DC_GPIO_Port,  ST7796_DC_Pin,  GPIO_PIN_RESET) /* select SPI command mode for the next transfer */

#ifndef ST7796_CFG_NO_CS
#define ST7796_CS_Clr()     HAL_GPIO_WritePin(ST7796_CS_GPIO_Port,  ST7796_CS_Pin,  GPIO_PIN_RESET) /* assert software chip select for the display */
#define ST7796_CS_Set()     HAL_GPIO_WritePin(ST7796_CS_GPIO_Port,  ST7796_CS_Pin,  GPIO_PIN_SET) /* deassert software chip select for the display */
#else
#define ST7796_CS_Clr()     do {} while(0) /* no-op chip-select assert when CS is tied permanently active */
#define ST7796_CS_Set()     do {} while(0) /* no-op chip-select deassert when CS is tied permanently active */
#endif

