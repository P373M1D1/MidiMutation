#!/usr/bin/env python3
"""
gen_gallery.py – Gallery image converter for ChatTest firmware.

Reads every image file found in the gallery/ folder at the project root,
rescales each one to 448×300 pixels using high-quality Lanczos resampling,
converts the pixels to RGB565 (big-endian, matching ST7796 byte order), and
writes two output files:

    Core/Inc/gallery_images.h   – stable header: GalleryImage_t type + extern decls
    Core/Src/gallery_images.c   – generated source: pixel arrays + registry table

Run from the project root:
    python tools/gen_gallery.py

Requires Pillow:
    pip install Pillow
"""

import os
import sys
import struct
from pathlib import Path

# ---------------------------------------------------------------------------
# Configuration
# ---------------------------------------------------------------------------

SCRIPT_DIR   = Path(__file__).resolve().parent
PROJECT_ROOT = SCRIPT_DIR.parent
GALLERY_DIR  = PROJECT_ROOT / "gallery"
OUT_H        = PROJECT_ROOT / "Core" / "Inc" / "gallery_images.h"
OUT_C        = PROJECT_ROOT / "Core" / "Src" / "gallery_images.c"

# Slightly reduced from full-panel to keep internal-flash builds viable.
DISPLAY_W = 448
DISPLAY_H = 300

# Files in the gallery folder with these extensions are treated as images.
IMAGE_EXTENSIONS = {".jpg", ".jpeg", ".png", ".bmp", ".gif", ".webp", ".tif", ".tiff"}


def rgb888_to_rgb565(r: int, g: int, b: int) -> int:
    """Convert a single RGB888 triplet to an RGB565 word (big-endian)."""
    return ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3)


def image_to_rgb565_array(img_path: Path):
    """
    Open an image, resize it to DISPLAY_W×DISPLAY_H with Lanczos filtering,
    and return a list of RGB565 uint16 values (row-major, left-to-right,
    top-to-bottom).
    """
    try:
        from PIL import Image
    except ImportError:
        print("ERROR: Pillow is not installed. Run:  pip install Pillow")
        sys.exit(1)

    with Image.open(img_path) as im:
        # Preserve aspect ratio by fitting inside the target rectangle,
        # then centre-crop so the result is always exactly DISPLAY_W×DISPLAY_H.
        im = im.convert("RGB")
        orig_w, orig_h = im.size
        scale = max(DISPLAY_W / orig_w, DISPLAY_H / orig_h)
        new_w = int(orig_w * scale)
        new_h = int(orig_h * scale)
        im = im.resize((new_w, new_h), Image.LANCZOS)

        # Centre-crop to display dimensions.
        left = (new_w - DISPLAY_W) // 2
        top  = (new_h - DISPLAY_H) // 2
        im   = im.crop((left, top, left + DISPLAY_W, top + DISPLAY_H))

        pixels = []
        for y in range(DISPLAY_H):
            for x in range(DISPLAY_W):
                r, g, b = im.getpixel((x, y))
                pixels.append(rgb888_to_rgb565(r, g, b))
        return pixels


def c_identifier(name: str) -> str:
    """Turn an arbitrary filename stem into a valid C identifier."""
    ident = ""
    for ch in name:
        if ch.isalnum():
            ident += ch
        else:
            ident += "_"
    if ident and ident[0].isdigit():
        ident = "img_" + ident
    return ident or "img"


def collect_images():
    """Return a sorted list of image paths from the gallery folder."""
    if not GALLERY_DIR.is_dir():
        return []
    paths = []
    for entry in sorted(GALLERY_DIR.iterdir()):
        if entry.is_file() and entry.suffix.lower() in IMAGE_EXTENSIONS:
            paths.append(entry)
    return paths


def write_header(image_names: list[str]):
    """Write Core/Inc/gallery_images.h."""
    lines = [
        "/* gallery_images.h – AUTO-GENERATED by tools/gen_gallery.py",
        " * Do not edit by hand; run the script to regenerate.",
        " */",
        "",
        "#ifndef GALLERY_IMAGES_H",
        "#define GALLERY_IMAGES_H",
        "",
        "#include <stdint.h>",
        "",
        "#ifdef __cplusplus",
        'extern "C" {',
        "#endif",
        "",
        "/** Native display dimensions expected by the gallery renderer. */",
        f"#define GALLERY_IMAGE_WIDTH  {DISPLAY_W}U",
        f"#define GALLERY_IMAGE_HEIGHT {DISPLAY_H}U",
        "",
        "/** One entry in the compiled image registry. */",
        "typedef struct {",
        "    const uint16_t *data; /**< RGB565 pixel data, row-major. */",
        "    const char     *name; /**< Human-readable label shown in gallery. */",
        "} GalleryImage_t;",
        "",
        "/** Flat array of all compiled gallery images (may be empty). */",
        "extern const GalleryImage_t gallery_images[];",
        "",
        "/** Number of entries in gallery_images[]. */",
        f"extern const uint8_t gallery_image_count; /* {len(image_names)} image(s) */",
        "",
        "#ifdef __cplusplus",
        "}",
        "#endif",
        "",
        "#endif /* GALLERY_IMAGES_H */",
        "",
    ]
    OUT_H.write_text("\n".join(lines), encoding="utf-8")
    print(f"  Wrote {OUT_H.relative_to(PROJECT_ROOT)}")


def write_source(images: list[tuple[str, list[int], str]]):
    """
    Write Core/Src/gallery_images.c.
    images is a list of (c_ident, pixel_list, display_name) tuples.
    """
    out = []
    out.append("/* gallery_images.c – AUTO-GENERATED by tools/gen_gallery.py")
    out.append(" * Do not edit by hand; run the script to regenerate.")
    out.append(" */")
    out.append("")
    out.append('#include "gallery_images.h"')
    out.append("")

    # Emit one pixel array per image.
    for ident, pixels, _name in images:
        total = len(pixels)
        out.append(f"/* {total} pixels ({DISPLAY_W}×{DISPLAY_H} RGB565) */")
        out.append(f"static const uint16_t gallery_data_{ident}[{DISPLAY_W}U * {DISPLAY_H}U] = {{")
        # Emit 16 values per line for readability.
        for i in range(0, total, 16):
            chunk = pixels[i:i + 16]
            out.append("    " + ",".join(f"0x{v:04X}" for v in chunk) + ",")
        out.append("};")
        out.append("")

    # Registry table.
    out.append("const GalleryImage_t gallery_images[] = {")
    if images:
        for ident, _pixels, name in images:
            safe_name = name.replace('"', '\\"')
            out.append(f'    {{ gallery_data_{ident}, "{safe_name}" }},')
    else:
        out.append("    /* no images – drop files into gallery/ and re-run gen_gallery.py */")
    out.append("};")
    out.append("")
    out.append(f"const uint8_t gallery_image_count = {len(images)}U;")
    out.append("")

    OUT_C.write_text("\n".join(out), encoding="utf-8")
    print(f"  Wrote {OUT_C.relative_to(PROJECT_ROOT)}")


def main():
    print("gen_gallery.py – ChatTest gallery image converter")
    print(f"  Gallery folder : {GALLERY_DIR}")
    print(f"  Target size    : {DISPLAY_W}×{DISPLAY_H} RGB565")
    print()

    image_paths = collect_images()

    if not image_paths:
        print("  No images found in gallery/ – writing empty registry.")
        write_header([])
        write_source([])
        print("\nDone.  Drop images into gallery/ and re-run to add them.")
        return

    images = []
    for path in image_paths:
        print(f"  Converting: {path.name}")
        ident   = c_identifier(path.stem)
        pixels  = image_to_rgb565_array(path)
        display = path.stem.replace("_", " ")
        images.append((ident, pixels, display))

    print()
    write_header([name for _, _, name in images])
    write_source(images)
    print(f"\nDone.  {len(images)} image(s) compiled into firmware.")


if __name__ == "__main__":
    main()
