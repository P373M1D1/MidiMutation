#!/usr/bin/env python3
"""
gen_consolas_40.py  –  Generate Consolas bitmap fonts for ST7796 driver.

Output: Drivers/ST7796/font_consolas_<W>x<H>.c

Requirements:
    pip install Pillow

Usage (defaults generate the 42pt large font):
    python tools/gen_consolas_40.py
    python tools/gen_consolas_40.py --size 28   # generate small font
"""

import os
import sys
import argparse

try:
    from PIL import Image, ImageDraw, ImageFont
except ImportError:
    print("ERROR: Pillow not installed.  Run:  pip install Pillow")
    sys.exit(1)

FONT_TTF   = r"C:\Windows\Fonts\consola.ttf"
THRESHOLD  = 96

# ── Helpers ───────────────────────────────────────────────────────────────────

def render_glyph(font, ch, cell_w, cell_h, baseline, threshold):
    img  = Image.new("L", (cell_w, cell_h), 0)
    draw = ImageDraw.Draw(img)
    ascent, _ = font.getmetrics()
    bbox = font.getbbox(ch)
    glyph_w = bbox[2] - bbox[0]
    x_off = (cell_w - glyph_w) // 2 - bbox[0]
    y_off = baseline - ascent
    draw.text((x_off, y_off), ch, fill=255, font=font)
    rows = []
    for row in range(cell_h):
        val = 0
        for col in range(cell_w):
            if img.getpixel((col, row)) >= threshold:
                val |= (0x80000000 >> col)
        rows.append(val & 0xFFFFFFFF)
    return rows

# ── Main ──────────────────────────────────────────────────────────────────────

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--size", type=int, default=42,
                        help="Consolas point size (default: 42)")
    args = parser.parse_args()

    if not os.path.exists(FONT_TTF):
        print(f"ERROR: Consolas TTF not found at:\n  {FONT_TTF}")
        sys.exit(1)

    font_size = args.size
    print(f"Loading {FONT_TTF} at size {font_size}…")
    font = ImageFont.truetype(FONT_TTF, font_size)

    cell_w   = int(font.getlength("M"))
    ascent, descent = font.getmetrics()
    cell_h   = ascent + descent + 6   # 3px padding top and bottom
    baseline = ascent + 3
    print(f"Cell size: {cell_w} x {cell_h} px  (baseline row {baseline})")

    struct_name = f"Font_Consolas{cell_w}x{cell_h}"
    table_name  = f"Consolas{cell_w}x{cell_h}_Table"
    out_name    = f"font_consolas_{cell_w}x{cell_h}.c"
    out_path    = os.path.normpath(
        os.path.join(os.path.dirname(__file__),
                     "..", "Drivers", "ST7796", out_name))

    lines = []
    lines.append(f"/* {out_name}")
    lines.append(f" * Consolas {cell_w}x{cell_h} bitmap font for ST7796 driver.")
    lines.append( " * AUTO-GENERATED by tools/gen_consolas_40.py  –  DO NOT EDIT.")
    lines.append(f" * Cell size : {cell_w} x {cell_h} px   TTF size: {font_size} pt")
    lines.append( " */")
    lines.append("")
    lines.append('#include "fonts.h"')
    lines.append("")
    lines.append(f"static const uint32_t {table_name}[] = {{")

    for code in range(32, 127):
        ch   = chr(code)
        rows = render_glyph(font, ch, cell_w, cell_h, baseline, THRESHOLD)
        lines.append(f"    /* 0x{code:02X}  {repr(ch)} */")
        for i in range(0, len(rows), 8):
            chunk = ", ".join(f"0x{v:08X}U" for v in rows[i:i+8])
            lines.append(f"    {chunk},")

    lines.append("};")
    lines.append("")
    lines.append(f"FontDef32 {struct_name} = {{")
    lines.append(f"    .width  = {cell_w}U,")
    lines.append(f"    .height = {cell_h}U,")
    lines.append(f"    .data   = {table_name},")
    lines.append("};")
    lines.append("")

    with open(out_path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))

    print(f"Done.  Written 95 glyphs ({cell_w}x{cell_h}) to:\n  {out_path}")
    print(f"Struct name: {struct_name}")
    return cell_w, cell_h, struct_name

if __name__ == "__main__":
    main()

