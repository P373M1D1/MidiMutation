#!/usr/bin/env python3
"""
Generate the DOS BIOS-inspired bitmap fonts used by the display theme.

The source glyphs stay local to the repo: printable ASCII comes from the
existing 10x14 bitmap font and is scaled into the UI cell sizes with extra
horizontal breathing room and a less aggressive aspect ratio than the first
BIOS pass.
"""

from __future__ import annotations

from pathlib import Path
import re


ASCII_FIRST = 32
ASCII_LAST = 126
GLYPH_COUNT = ASCII_LAST - ASCII_FIRST + 1
SOURCE_GLYPH_WIDTH = 10
SOURCE_GLYPH_HEIGHT = 14
BIOS_PIXEL_ASPECT_NUM = 15
BIOS_PIXEL_ASPECT_DEN = 8

ROOT = Path(__file__).resolve().parent.parent
FONT_10X14_INC = ROOT / "Drivers" / "ST7796" / "font_10x14.inc"
OUT_DIR = ROOT / "Drivers" / "ST7796"


def parse_font10x14_source() -> dict[str, list[int]]:
    text = FONT_10X14_INC.read_text(encoding="utf-8")
    values = [int(value, 16) for value in re.findall(r"0x([0-9A-Fa-f]+)", text)]
    if len(values) != GLYPH_COUNT * SOURCE_GLYPH_HEIGHT:
        raise RuntimeError(f"unexpected font_10x14.inc glyph table length: {len(values)}")

    glyphs: dict[str, list[int]] = {}
    for glyph_index in range(GLYPH_COUNT):
        rows16 = values[glyph_index * SOURCE_GLYPH_HEIGHT:(glyph_index + 1) * SOURCE_GLYPH_HEIGHT]
        glyphs[chr(ASCII_FIRST + glyph_index)] = [((row >> 6) & 0x03FF) for row in rows16]

    return glyphs


def scale_bitmap(src_rows: list[int], src_w: int, src_h: int, dst_w: int, dst_h: int) -> list[int]:
    scaled: list[int] = []
    for y in range(dst_h):
        src_y = min(src_h - 1, (y * src_h) // dst_h)
        src_row = src_rows[src_y]
        out_row = 0
        for x in range(dst_w):
            src_x = min(src_w - 1, (x * src_w) // dst_w)
            if src_row & (1 << (src_w - 1 - src_x)):
                out_row |= 1 << (dst_w - 1 - x)
        scaled.append(out_row)
    return scaled


def build_bios_glyphs() -> dict[str, list[int]]:
    return parse_font10x14_source()


def compose_font_rows(src_rows: list[int], cell_w: int, cell_h: int, pad_x: int, pad_y: int) -> list[int]:
    inner_w = cell_w - (pad_x * 2)
    inner_h = cell_h - (pad_y * 2)
    target_h = (inner_w * BIOS_PIXEL_ASPECT_NUM + (BIOS_PIXEL_ASPECT_DEN // 2)) // BIOS_PIXEL_ASPECT_DEN

    if inner_w <= 0 or inner_h <= 0:
        raise ValueError("invalid cell height")

    if target_h <= 0:
        raise ValueError("invalid scaled glyph height")

    if target_h > inner_h:
        target_h = inner_h

    pad_y = (cell_h - target_h) // 2
    scaled = scale_bitmap(src_rows, SOURCE_GLYPH_WIDTH, SOURCE_GLYPH_HEIGHT, inner_w, target_h)
    out_rows = [0] * cell_h

    for y, row_bits in enumerate(scaled):
        packed = 0
        for x in range(inner_w):
            if row_bits & (1 << (inner_w - 1 - x)):
                packed |= 1 << (31 - (pad_x + x))
        out_rows[pad_y + y] = packed

    return out_rows


def write_font_file(file_name: str,
                    struct_name: str,
                    cell_w: int,
                    cell_h: int,
                    pad_x: int,
                    pad_y: int,
                    glyphs: dict[str, list[int]]) -> None:
    table_name = f"{struct_name}_Table"
    lines: list[str] = [
        f"/* {file_name}",
        " * DOS BIOS-inspired bitmap font for ST7796 driver.",
        " * AUTO-GENERATED by tools/gen_bios_theme_font.py - DO NOT EDIT.",
        f" * Cell size : {cell_w} x {cell_h} px   Base grid: 8 x 16 px",
        " */",
        "",
        '#include "fonts.h"',
        "",
        f"static const uint32_t {table_name}[] = {{",
    ]

    for code in range(ASCII_FIRST, ASCII_LAST + 1):
        ch = chr(code)
        rows = compose_font_rows(glyphs[ch], cell_w, cell_h, pad_x, pad_y)
        lines.append(f"    /* 0x{code:02X}  {ch!r} */")
        for index in range(0, len(rows), 8):
            chunk = ", ".join(f"0x{value:08X}U" for value in rows[index:index + 8])
            lines.append(f"    {chunk},")

    lines.extend([
        "};",
        "",
        f"FontDef32 {struct_name} = {{",
        f"    .width  = {cell_w}U,",
        f"    .height = {cell_h}U,",
        f"    .data   = {table_name},",
        "};",
        "",
    ])

    (OUT_DIR / file_name).write_text("\n".join(lines), encoding="utf-8")


def main() -> None:
    glyphs = build_bios_glyphs()
    write_font_file("font_bios_8x21.c", "Font_BIOS_8x21", 8, 21, 0, 2, glyphs)
    write_font_file("font_bios_15x35.c", "Font_BIOS_15x35", 15, 35, 1, 3, glyphs)
    write_font_file("font_bios_23x49.c", "Font_BIOS_23x49", 23, 49, 2, 4, glyphs)
    print("Generated BIOS theme fonts:")
    print("  Drivers/ST7796/font_bios_8x21.c")
    print("  Drivers/ST7796/font_bios_15x35.c")
    print("  Drivers/ST7796/font_bios_23x49.c")


if __name__ == "__main__":
    main()